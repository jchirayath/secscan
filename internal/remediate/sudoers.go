package remediate

import (
	"sort"
	"strings"
)

// PrivilegedCommands returns every command the green playbooks need to run as
// root, de-duplicated. Amber and red are excluded on purpose: this tool will
// never run them, so granting privilege for them would widen the account's
// reach for no benefit.
func PrivilegedCommands() [][]string {
	seen := map[string]bool{}
	var out [][]string
	add := func(cmds [][]string) {
		for _, c := range cmds {
			k := strings.Join(c, "\x00")
			if !seen[k] {
				seen[k] = true
				out = append(out, c)
			}
		}
	}
	for _, raw := range catalogue {
		p := normalise(raw)
		if !p.Executable() || !p.Privileged {
			continue
		}
		add(p.Apply)
		add(p.Rollback)
	}
	sort.Slice(out, func(i, j int) bool {
		return strings.Join(out[i], " ") < strings.Join(out[j], " ")
	})
	return out
}

// Sudoers renders exact-match sudoers entries for the commands above.
//
// resolve maps a bare command name to its absolute path on the target; sudo
// matches on the resolved path, so a rule written against a bare name never
// matches. If resolve returns "", the bare name is emitted and the operator has
// to fill it in — which is better than emitting a guessed path that silently
// fails to match.
//
// Every argument is escaped and no wildcard is ever emitted. That is the whole
// point of generating this: the obvious hand-written shortcut is
//
//	secscan ALL=(root) NOPASSWD: /usr/bin/sh -c *
//
// and that single line is indistinguishable from unrestricted root. Exact
// argument matching means the account can run precisely these strings and
// nothing else.
func Sudoers(user string, resolve func(string) string) []string {
	out := []string{
		"# secscan remediation — generated by `secscan fix -sudoers`.",
		"#",
		"# These entries let the scanning account apply ONLY the green fixes, and",
		"# only with exactly these arguments. Review every line before installing.",
		"#",
		"# Do NOT replace an argument list with a wildcard. `/usr/bin/sh -c *` is",
		"# not a narrower grant than ALL — it is the same grant, spelled longer.",
		"#",
		"# Install with:",
		"#   sudo visudo -c -f <thisfile> && sudo install -m 440 <thisfile> /etc/sudoers.d/secscan-remediate",
		"",
	}
	for _, c := range UnrepresentableInSudoers() {
		out = append(out,
			"# WARNING: this command contains a newline and cannot be pinned by an exact",
			"# sudoers rule. Apply it by hand rather than granting it with a wildcard:",
			"#   "+strings.ReplaceAll(c, "\n", "\\n"),
			"")
	}
	for _, argv := range PrivilegedCommands() {
		if len(argv) == 0 {
			continue
		}
		parts := make([]string, 0, len(argv))
		path := resolve(argv[0])
		if path == "" {
			path = argv[0]
			out = append(out, "# NOTE: could not resolve an absolute path for "+argv[0]+
				" on this host; sudo will not match a bare name.")
		}
		parts = append(parts, path)
		for _, a := range argv[1:] {
			parts = append(parts, sudoersEscape(a))
		}
		out = append(out, user+" ALL=(root) NOPASSWD: "+strings.Join(parts, " "))
	}
	return out
}

// sudoersEscape makes one argument match literally.
//
// Only the characters sudoers actually defines an escape for are escaped:
// backslash, whitespace, comma, colon, equals, and the glob characters. Two
// intuitive approaches both fail, and both were tried against visudo before
// this one:
//
//   - escaping every shell metacharacter — `\>` and `\'` are not escapes in
//     sudoers, they are syntax errors
//   - wrapping the argument in double quotes — sudoers splits a command list on
//     commas before quoting is considered, so an argument containing a comma
//     becomes a second, malformed command entry
//
// Glob characters are escaped because sudo matches command arguments as
// patterns: an unescaped `*` would silently widen the grant far beyond the
// literal string it was meant to pin.
func sudoersEscape(s string) string {
	if s == "" {
		return `""`
	}
	// Interpreted, not raw: in a raw string `\t` is backslash-then-t, so the set
	// would match every letter t and every backslash and mangle /etc into /e\tc.
	const escapes = "\\ \t,:=*?[]"
	var b strings.Builder
	for _, r := range s {
		if strings.ContainsRune(escapes, r) {
			b.WriteByte('\\')
		}
		b.WriteRune(r)
	}
	return b.String()
}

// UnrepresentableInSudoers reports commands that cannot be pinned by an exact
// sudoers rule, so the caller can say so rather than emit a line that visudo
// accepts and sudo never matches. A literal newline in an argument is the case
// that matters: sudoers has no way to express one.
func UnrepresentableInSudoers() []string {
	var bad []string
	for _, argv := range PrivilegedCommands() {
		for _, a := range argv {
			if strings.ContainsAny(a, "\n\r") {
				bad = append(bad, strings.Join(argv, " "))
				break
			}
		}
	}
	return bad
}
