#!/usr/bin/env bash
# Upstream watch: what changed on the internet that secscan should know about.
#
# Renovate answers "is there a newer version?" and opens the bump PR. It cannot
# answer the questions that decide whether that PR is safe or whether secscan is
# falling behind:
#   - did the engine change a CLI flag, its JSON output, or an exit code?
#     (those are what break an adapter; the contract tests prove it, this says
#     where to look)
#   - what detection content arrived — new gitleaks rules, new nuclei templates?
#   - is the Go toolchain still supported (secscan is stdlib-only, so the
#     toolchain IS its dependency tree), and does govulncheck find anything?
#   - has a tool we decided to integrate later (docs/TOOL-LANDSCAPE.md) moved?
#
# Output is a Markdown report on stdout; the weekly workflow files it as one
# rolling issue labelled upstream-watch (the engineering standard's
# sources-weekly pattern: open, update, close when clear).
#
# Exit: 0 nothing needs a human · 1 something does · 2 the check itself failed.
#
# Needs: gh (authenticated; GH_TOKEN in CI), curl, sort -V.
# Optional env: CANARY=pass|fail|skip (result of the latest-engines contract run),
#               GOVULN_FILE=path (govulncheck text output to fold in).
set -uo pipefail
cd "$(dirname "$0")/.."

COOLDOWN_DAYS=7
attention=0
need() { attention=1; }
now=$(date -u +%s)
days_since() { echo $(( (now - $(date -u -d "$1" +%s 2>/dev/null || date -u -j -f '%Y-%m-%dT%H:%M:%SZ' "$1" +%s)) / 86400 )); }
newer() { [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | tail -1)" = "$1" ]; }

command -v gh >/dev/null || { echo "upstream.sh: gh is required" >&2; exit 2; }
gh api rate_limit >/dev/null 2>&1 || { echo "upstream.sh: gh is not authenticated" >&2; exit 2; }

# Lines in release notes that matter to an ADAPTER: anything touching flags,
# output format, exit codes, defaults or removals. Everything else (perf,
# docs, internal refactors) is noise for this purpose.
# Kept narrow on purpose: a report where every line is flagged gets skimmed,
# and then the one line that matters is missed.
RISK_RE='BREAKING|[Bb]reaking|READ THIS|[Dd]eprecat|JSON|json|[Ee]xit code|[Rr]enam|[Rr]emoved? .*(flag|option|field|command)'
# Lines that announce capability secscan might want to adopt.
FEAT_RE='^[*-] *(feat|[Aa]dd|[Nn]ew|[Ss]upport|[Ii]ntroduc)'

echo "# Upstream watch — $(date -u +%F)"
echo
echo "Generated by \`ci/upstream.sh\` (weekly, \`.github/workflows/upstream-weekly.yml\`)."
echo "Version bumps arrive as Renovate PRs after a ${COOLDOWN_DAYS}-day cooldown; this issue is the"
echo "secscan-specific reading of what changed and what needs a human."
echo

# ------------------------------------------------------------------ engines
echo "## Engines"
echo
echo "| Engine | Pinned | Latest | Released | Status |"
echo "|---|---|---|---|---|"
details=""
while read -r eng pinned; do
  case "$eng" in
    gitleaks) repo=gitleaks/gitleaks ;;
    osv-scanner) repo=google/osv-scanner ;;
    nuclei) repo=projectdiscovery/nuclei ;;
    testssl) repo=testssl/testssl.sh ;;
    trivy) repo=aquasecurity/trivy ;;
    *) continue ;;
  esac
  rels=$(gh api "repos/$repo/releases?per_page=40" \
    --jq '.[] | select(.draft|not) | select(.prerelease|not) | [.tag_name, .published_at] | @tsv' 2>/dev/null) \
    || { echo "| $eng | $pinned | ? | ? | lookup failed |"; need; continue; }
  latest_tag=$(echo "$rels" | head -1 | cut -f1); latest=${latest_tag#v}
  latest_at=$(echo "$rels" | head -1 | cut -f2)
  age=$(days_since "$latest_at")
  status="current"
  if newer "$latest" "$pinned"; then
    major_p=${pinned%%.*}; major_l=${latest%%.*}
    if [ "$major_l" != "$major_p" ]; then status="**major update** — expect CLI/output changes"; need
    elif [ "$age" -lt "$COOLDOWN_DAYS" ]; then status="update in cooldown ($((COOLDOWN_DAYS-age))d left)"
    else status="update available — Renovate PR due"; fi
    # Summarise every release between the pin and latest.
    block="### $eng $pinned → $latest\n\n"
    shown=0 older=0
    while IFS=$'\t' read -r tag at; do
      v=${tag#v}
      newer "$v" "$pinned" || continue
      # Newest ten in detail; a long gap is summarised so the issue stays
      # readable (and under GitHub's body limit).
      if [ "$shown" -ge 10 ]; then older=$((older+1)); continue; fi
      shown=$((shown+1))
      body=$(gh api "repos/$repo/releases/tags/$tag" --jq '.body // ""' 2>/dev/null | tr -d '\r')
      risk=$(echo "$body" | grep -E "$RISK_RE" | grep -vE '^(#|    )|dependabot|[Bb]ump ' | head -4 | cut -c1-220 | sed 's/^[*-] *//; s/^/  - ⚠ /')
      feat=$(echo "$body" | grep -E "$FEAT_RE" | grep -vE "dependabot|[Bb]ump |$RISK_RE" | head -3 | cut -c1-220 | sed 's/^[*-] */  - /')
      block+="- **$tag** ($(echo "$at" | cut -c1-10)) — https://github.com/$repo/releases/tag/$tag\n"
      [ -n "$risk" ] && block+="$risk\n"
      [ -n "$feat" ] && block+="$feat\n"
      [ -n "$risk" ] && need
    done <<< "$rels"
    [ "$older" -gt 0 ] && block+="- … and $older older release(s) since $pinned: https://github.com/$repo/releases\n"
    details+="$block\n"
  fi
  echo "| $eng | $pinned | $latest | $(echo "$latest_at" | cut -c1-10) | $status |"
done < <(ci/engines.sh versions)
echo
echo "⚠ marks release-note lines touching flags, output, exit codes, defaults or removals — read"
echo "them against the adapter in \`internal/core/engine/\` before merging the bump."
echo
if [ -n "$details" ]; then printf '%b' "$details"; fi

# ------------------------------------------------------------- canary run
echo "## Latest-upstream canary"
echo
case "${CANARY:-skip}" in
  pass) echo "✅ The engine contract tests passed against **every engine's latest release** — the pending bumps are safe for the adapters." ;;
  fail) echo "❌ The engine contract tests **failed** against the latest upstream releases. An adapter needs updating before (or with) the next bump; see the workflow run's \`canary\` job."; need ;;
  *)    echo "_Not run in this invocation._" ;;
esac
echo

# ----------------------------------------------------------- rule content
echo "## Detection content"
echo
# gitleaks compiles its rules into the binary, so new rules reach secscan only
# by moving the pin. Diff the rule IDs between the pinned and latest tags.
gl_pin=$(ci/engines.sh versions | awk '$1=="gitleaks"{print $2}')
gl_latest=$(gh api repos/gitleaks/gitleaks/releases/latest --jq '.tag_name' 2>/dev/null | sed 's/^v//')
rules() { curl -fsSL "https://raw.githubusercontent.com/gitleaks/gitleaks/v$1/config/gitleaks.toml" 2>/dev/null \
  | sed -nE 's/^id = "([^"]+)".*/\1/p' | sort -u; }
if [ -n "$gl_latest" ] && [ "$gl_latest" != "$gl_pin" ]; then
  a=$(rules "$gl_pin"); b=$(rules "$gl_latest")
  added=$(comm -13 <(echo "$a") <(echo "$b")); removed=$(comm -23 <(echo "$a") <(echo "$b"))
  echo "- **gitleaks rules** ($gl_pin → $gl_latest): $(echo "$added" | grep -c .) added, $(echo "$removed" | grep -c .) removed. They ship inside the binary, so the engine bump PR delivers them."
  [ -n "$added" ] && echo "  - added: $(echo "$added" | head -40 | paste -sd, - | sed 's/,/, /g')"
  [ -n "$removed" ] && echo "  - removed: $(echo "$removed" | paste -sd, - | sed 's/,/, /g') — check no secscan finding relies on these rule IDs"
  [ -n "$removed" ] && need
else
  echo "- **gitleaks rules**: pinned version is latest."
fi
# nuclei templates and the trivy DB are fetched at run time by the engines
# themselves, so they need no PR — reported so the operator knows what arrived.
nt=$(gh api repos/projectdiscovery/nuclei-templates/releases/latest --jq '[.tag_name, .published_at] | @tsv' 2>/dev/null)
if [ -n "$nt" ]; then
  nt_tag=$(echo "$nt" | cut -f1); nt_at=$(echo "$nt" | cut -f2 | cut -c1-10)
  cves=$(gh api "repos/projectdiscovery/nuclei-templates/releases/tags/$nt_tag" --jq '.body // ""' 2>/dev/null \
    | grep -oE 'CVE-[0-9]{4}-[0-9]+' | sort -u)
  echo "- **nuclei-templates** $nt_tag ($nt_at): $(echo "$cves" | grep -c .) CVE templates named in the release notes. Fetched by nuclei at run time (no PR needed); secscan's nuclei engine stays opt-in."
  [ -n "$cves" ] && echo "  - $(echo "$cves" | head -15 | paste -sd, - | sed 's/,/, /g')$( [ "$(echo "$cves" | grep -c .)" -gt 15 ] && echo ', …')"
fi
echo "- **trivy vulnerability DB**: refreshed by trivy itself every run (no PR needed)."
echo

# ------------------------------------------------------------- Go toolchain
echo "## Go toolchain"
echo
gomod=$(sed -nE 's/^go ([0-9.]+).*/\1/p' go.mod)
supported=$(curl -fsSL 'https://go.dev/dl/?mode=json' 2>/dev/null | tr ',' '\n' | sed -nE 's/.*"version": *"go([0-9.]+)".*/\1/p' | sort -uV)
if [ -z "$supported" ]; then
  echo "- could not read go.dev release list"; need
else
  latest_go=$(echo "$supported" | sort -V | tail -1)
  mm=$(echo "$gomod" | cut -d. -f1,2)
  if echo "$supported" | cut -d. -f1,2 | grep -qx "$mm"; then
    echo "- go.mod: \`go $gomod\` — supported (current releases: $(echo "$supported" | paste -sd' ' -))."
  else
    echo "- go.mod: \`go $gomod\` — **out of support**: Go $mm receives no security fixes. Supported: $(echo "$supported" | paste -sd' ' -). Merge the Renovate Go toolchain PR (review: minor bump)."
    need
  fi
fi
if [ -n "${GOVULN_FILE:-}" ] && [ -s "$GOVULN_FILE" ]; then
  if grep -q 'No vulnerabilities found' "$GOVULN_FILE"; then
    echo "- govulncheck: no reachable vulnerabilities."
  else
    echo "- **govulncheck found reachable vulnerabilities** — security fixes are exempt from the cooldown; bump the toolchain now:"
    echo; echo '```'; grep -E '^(Vulnerability #|  *Found in|  *Fixed in|  *More info)' "$GOVULN_FILE" | head -40; echo '```'
    need
  fi
fi
echo

# ------------------------------------------------------ candidate engines
# Tools docs/TOOL-LANDSCAPE.md chose to integrate later. Integration is a design
# decision (a new adapter, a fixture, a contract test, an install recipe), so
# this only reports liveness; a human opens the feature issue.
echo "## Candidate engines (docs/TOOL-LANDSCAPE.md, not yet integrated)"
echo
echo "| Tool | Latest | Released | Note |"
echo "|---|---|---|---|"
for repo in anchore/grype CISOfy/lynis future-architect/vuls OpenSCAP/openscap; do
  r=$(gh api "repos/$repo/releases/latest" --jq '[.tag_name, .published_at] | @tsv' 2>/dev/null)
  arch=$(gh api "repos/$repo" --jq '.archived' 2>/dev/null)
  note="—"; [ "$arch" = "true" ] && note="**archived** — drop from the landscape"
  if [ -n "$r" ]; then echo "| [$repo](https://github.com/$repo) | $(echo "$r" | cut -f1) | $(echo "$r" | cut -f2 | cut -c1-10) | $note |"
  else echo "| [$repo](https://github.com/$repo) | ? | ? | lookup failed |"; fi
done
echo
echo "To adopt one: open an issue, then a PR that adds the adapter in \`internal/core/engine/\`,"
echo "an install recipe with a \`renovate:\` pin, a contract test, and a TOOL-LANDSCAPE update."
echo
echo "---"
if [ "$attention" -eq 1 ]; then echo "**Needs a human:** yes — see the items marked above."; else echo "**Needs a human:** no."; fi
exit "$attention"
